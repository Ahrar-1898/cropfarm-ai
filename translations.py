def format_localized_date(value: date, language: str) -> str:
    month_names = _MONTH_NAMES.get(language, _MONTH_NAMES["en"])
    if language not in _LOCAL_DIGITS:
        return f"{month_names[value.month - 1]} {value.day:02d}, {value.year}"
    day = f"{value.day:02d}".translate(_LOCAL_DIGITS[language])
    year = str(value.year).translate(_LOCAL_DIGITS[language])
    return f"{day} {month_names[value.month - 1]} {year}"
